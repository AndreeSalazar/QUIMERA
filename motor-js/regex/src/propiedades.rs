/// Los rangos de la propiedad `nombre` (lo que va entre las llaves de `\p{...}`), o `None` si
/// QUIMERA no la conoce (y entonces el patrón no es válido, como en los navegadores).
pub(crate) fn rangos(nombre: &str) -> Option<Vec<(u32, u32)>> {
    if let Some((clave, valor)) = nombre.split_once('=') {
        return match clave {
            "Script" | "sc" | "Script_Extensions" | "scx" => alfabeto(valor).map(<[_]>::to_vec),
            "General_Category" | "gc" => rangos(valor),
            _ => None,
        };
    }
    let tabla = |t: &[(u32, u32)]| Some(t.to_vec());
    match nombre {
        "L" | "Letter" | "Alphabetic" | "Alpha" => Some(recorrer(char::is_alphabetic)),
        "ID_Start" | "IDS" | "XID_Start" | "XIDS" => Some(recorrer(char::is_alphabetic)),
        "ID_Continue" | "IDC" | "XID_Continue" | "XIDC" => {
            let mut v = recorrer(|c| c.is_alphanumeric());
            v.extend_from_slice(MARCAS);
            v.push((0x5f, 0x5f));
            Some(v)
        }
        "Lu" | "Uppercase_Letter" | "Uppercase" | "Upper" => Some(recorrer(char::is_uppercase)),
        "Ll" | "Lowercase_Letter" | "Lowercase" | "Lower" => Some(recorrer(char::is_lowercase)),
        "N" | "Number" | "Nd" | "Decimal_Number" | "digit" => Some(recorrer(char::is_numeric)),
        "P" | "Punctuation" | "punct" => tabla(PUNTUACION),
        "S" | "Symbol" => tabla(SIMBOLOS),
        "M" | "Mark" | "Combining_Mark" | "Mn" | "Nonspacing_Mark" => tabla(MARCAS),
        "Z" | "Separator" | "Zs" | "Space_Separator" => tabla(ESPACIOS),
        "White_Space" | "space" => Some([ESPACIOS, BLANCOS].concat()),
        "Cc" | "Control" | "cntrl" => tabla(CONTROL),
        "Extended_Pictographic" | "ExtPict" | "Emoji_Presentation" | "EPres" => tabla(PICTOGRAMAS),
        "Emoji" => Some([PICTOGRAMAS, EMOJI_EXTRA].concat()),
        "Regional_Indicator" | "RI" => tabla(&[(0x1f1e6, 0x1f1ff)]),
        "Emoji_Modifier" | "EMod" => tabla(&[(0x1f3fb, 0x1f3ff)]),
        "Emoji_Modifier_Base" | "EBase" => tabla(PICTOGRAMAS),
        "Emoji_Component" | "EComp" => tabla(&[
            (0x23, 0x23),
            (0x2a, 0x2a),
            (0x30, 0x39),
            (0x200d, 0x200d),
            (0x20e3, 0x20e3),
            (0xfe0f, 0xfe0f),
            (0x1f1e6, 0x1f1ff),
            (0x1f3fb, 0x1f3ff),
            (0x1f9b0, 0x1f9b3),
            (0xe0020, 0xe007f),
        ]),
        "ASCII" => tabla(&[(0, 0x7f)]),
        "Any" => tabla(&[(0, 0x10_ffff)]),
        _ => alfabeto(nombre).map(<[_]>::to_vec),
    }
}

/// Los rangos de los caracteres que cumplen `cumple` (hasta [`TOPE`]).
fn recorrer(cumple: fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut v: Vec<(u32, u32)> = Vec::new();
    for c in (0..=TOPE).filter_map(char::from_u32).filter(|c| cumple(*c)) {
        let n = c as u32;
        match v.last_mut() {
            Some(r) if r.1 + 1 == n => r.1 = n,
            _ => v.push((n, n)),
        }
    }
    v
}
